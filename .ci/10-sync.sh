# Fetch the kleaf workspace for the OnePlus 15 (infiniti / SM8850 "canoe").
#
# The workspace is the same one LineageOS builds: `repo` at the kernel platform
# root, containing
#   - the GKI/ACK kernel and kleaf itself, pinned by the LineageOS manifest
#     snippet snippets/kernel-<ver>.xml (this is what makes the GKI source the
#     android16-6.12-2026-06 tag the PixelOS thread links to), plus
#   - the three OnePlus kernel repos, at the paths LineageOS' own
#     device/oneplus/sm8850-common/lineage.dependencies puts them.

set -euo pipefail
source "$(dirname "${BASH_SOURCE[0]}")/lib.sh"

export PATH="$HOME/bin:$PATH"
command -v repo >/dev/null 2>&1 || die "repo not found; run .ci/00-deps.sh first"

git config --global user.email "kernel-build@localhost"
git config --global user.name "kernel-build"
git config --global trailer.changeid.key "Change-Id"

mkdir -p "$KERNEL_PLATFORM"
cd "$KERNEL_PLATFORM"

if [ ! -d .repo ]; then
    log "repo init -u $MANIFEST_URL -b $KERNEL_BRANCH"
    repo init -u "$MANIFEST_URL" -b "$KERNEL_BRANCH" --no-clone-bundle --depth=1
else
    log "reusing existing repo workspace at $KERNEL_PLATFORM"
fi

log "Writing .repo/local_manifests/op15-oss-kernel.xml"
log "  CLO/SoC kernel: $CLO_REPO @ $CLO_REVISION ($CLO_REMOTE_FETCH)"
mkdir -p .repo/local_manifests

# Optional GKI/ACK pin override. Default "auto" keeps the revision the
# LineageOS snippet pins; anything else re-points kernel/common at a specific
# tag (e.g. android16-6.12-2026-09).
GKI_OVERRIDE=""
if [ -n "$GKI_REVISION" ] && [ "$GKI_REVISION" != "auto" ]; then
    warn "overriding the GKI/ACK revision with $GKI_REVISION"
    GKI_OVERRIDE="  <remove-project name=\"kernel/common\" />
  <project path=\"$PLATFORM_REL/common\" name=\"kernel/common\" remote=\"aosp\"
           revision=\"$GKI_REVISION\" upstream=\"$GKI_REVISION\" />
"
fi

cat > .repo/local_manifests/op15-oss-kernel.xml <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!--
  Generated by .ci/10-sync.sh. Do not edit in place.

  The include pulls in the LineageOS kleaf/GKI platform manifest for kernel
  $KERNEL_VERSION (kernel/build, kernel/common, kernel/prebuilts/build-tools,
  platform/prebuilts/*, external/*, tools/mkbootimg, ...). It also creates the
  repo linkfiles tools/bazel, MODULE.bazel and WORKSPACE.bzlmod at the
  workspace root, which is how kleaf is invoked in bzlmod mode.

  The three projects below are the OnePlus 15 kernel sources the PixelOS 17
  thread publishes as "GKI / CLO / Techpack modules / Techpack devicetrees".

  NOTE: XML comments may not contain a double hyphen, so keep them free of
  dashes when extending this block.
-->
<manifest>
  <remote name="los" fetch="https://github.com/LineageOS" />
  <remote name="clo" fetch="$CLO_REMOTE_FETCH" />

  <include name="manifests/snippets/$KERNEL_SNIPPET" />
$GKI_OVERRIDE
  <project path="$PLATFORM_REL/$KERNEL_SRC_REL"
           name="$CLO_REPO"
           remote="clo" revision="$CLO_REVISION" />
  <project path="$PLATFORM_REL/${KERNEL_SRC_REL}-modules"
           name="android_kernel_oneplus_sm8850-modules"
           remote="los" revision="$KERNEL_BRANCH" />
  <project path="$PLATFORM_REL/${KERNEL_SRC_REL}-devicetrees"
           name="android_kernel_oneplus_sm8850-devicetrees"
           remote="los" revision="$KERNEL_BRANCH" />
</manifest>
EOF

log "Resolving the merged manifest"
mkdir -p "$OUT"
FULL_MANIFEST="$OUT/manifest-full.xml"
repo manifest -o "$FULL_MANIFEST"

mapfile -t SYNC_PATHS < <(python3 "$REPO_ROOT/.ci/list-platform-paths.py" "$FULL_MANIFEST" "$PLATFORM_REL")
[ "${#SYNC_PATHS[@]}" -gt 0 ] || die "no projects found under $PLATFORM_REL"

log "Syncing ${#SYNC_PATHS[@]} projects (current branch only, depth 1)"
set -x
if ! repo sync -c --no-tags --force-sync --depth=1 -j"$JOBS" "${SYNC_PATHS[@]}"; then
    set +x
    warn "depth-1 sync failed; retrying with full history (slower, more disk)"
    repo sync -c --no-tags --force-sync -j"$JOBS" "${SYNC_PATHS[@]}"
fi
set +x

log "Verifying the workspace layout"
require_dir "$KERNEL_PATH/common"
require_dir "$KERNEL_PATH/build/kernel/kleaf"
require_dir "$SOC_REPO"
require_dir "$KERNEL_PATH/${KERNEL_SRC_REL}-modules"
require_dir "$KERNEL_PATH/${KERNEL_SRC_REL}-devicetrees"
require_file "$KERNEL_PATH/tools/bazel"

for f in MODULE.bazel WORKSPACE.bzlmod tools/bazel; do
    if [ ! -e "$KERNEL_PATH/$f" ]; then
        warn "$KERNEL_PATH/$f is missing (repo linkfile not created?)"
    fi
done

log "Pinned revisions"
printf '  %-46s %s\n' "kernel/common (GKI/ACK)" "$(git -C "$KERNEL_PATH/common" rev-parse --short HEAD 2>/dev/null || echo '?')"
printf '  %-46s %s\n' "kernel/build (kleaf)" "$(git -C "$KERNEL_PATH/build/kernel" rev-parse --short HEAD 2>/dev/null || echo '?')"
printf '  %-46s %s\n' "$KERNEL_SRC_REL (CLO/SoC)" "$(git -C "$SOC_REPO" rev-parse --short HEAD 2>/dev/null || echo '?')"
printf '  %-46s %s\n' "${KERNEL_SRC_REL}-modules" "$(git -C "$KERNEL_PATH/${KERNEL_SRC_REL}-modules" rev-parse --short HEAD 2>/dev/null || echo '?')"
printf '  %-46s %s\n' "${KERNEL_SRC_REL}-devicetrees" "$(git -C "$KERNEL_PATH/${KERNEL_SRC_REL}-devicetrees" rev-parse --short HEAD 2>/dev/null || echo '?')"

log "Workspace size"
du -sh "$KERNEL_PLATFORM" 2>/dev/null || true
df -h "$REPO_ROOT" || true
